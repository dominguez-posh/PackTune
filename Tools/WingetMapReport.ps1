# Report text of Tools\Update-WingetMap.ps1 (docs\winget-map-report.md)

function New-WingetMapReport {
    param($Build, $Data, [int]$IndexCount, [string]$Checked)
    $Curated = @($Data.catalog)
    $Top = @($Data.top)
    $CatalogWith = @($Curated | Where-Object { $_.winget }).Count
    $MapIds = @($Build.Map.Keys)
    $CuratedFilled = @($Curated | Where-Object { -not $_.winget -and $Build.Map.Contains($_.id.ToLower()) }).Count
    $TopMapped = @($Top | Where-Object { $Build.Map.Contains($_.ToLower()) }).Count
    $Titles = @{}; foreach ($I in @($Data.items)) { $Titles[$I.id.ToLower()] = $I.title }
    $L = New-Object System.Collections.ArrayList
    [void]$L.Add('# winget map report')
    [void]$L.Add('')
    [void]$L.Add("Generated by ``Tools\Update-WingetMap.ps1`` on $Checked from the winget source index ($IndexCount packages) and winget-pkgs manifests. Do not edit by hand: decisions go into ``data\winget-map-review.json``, then run the script again.")
    [void]$L.Add('')
    [void]$L.Add('## Coverage')
    [void]$L.Add('')
    [void]$L.Add('| List | Apps | winget id before | winget id with the map |')
    [void]$L.Add('|---|---|---|---|')
    [void]$L.Add("| Curated catalog | $($Curated.Count) | $CatalogWith | $($CatalogWith + $CuratedFilled) |")
    [void]$L.Add("| Popular top $($Top.Count) | $($Top.Count) | about 52 (strict name match at runtime) | $TopMapped |")
    [void]$L.Add('')
    [void]$L.Add("Map entries: $($Build.Map.Count) accepted, $($Build.Candidates.Count) candidates for review, $($Build.NoEquivalent.Count) without equivalent (reason), $($Build.None.Count) nothing found.")
    [void]$L.Add("Rule: accepted at score >= $($script:AcceptScore) with an identity signal and a lead of $($script:LeadScore) points; candidates from $($script:CandidateScore). The catalog winget id stays authoritative; the map only fills gaps.")
    [void]$L.Add('')
    $Conflicts = @($Curated | Where-Object { $_.winget -and $Build.Map.Contains($_.id.ToLower()) -and $Build.Map[$_.id.ToLower()].winget -ine $_.winget })
    [void]$L.Add("## Differences to the catalog ($($Conflicts.Count))")
    [void]$L.Add('')
    [void]$L.Add('The catalog winget id stays authoritative. Where the map finds another id, a person should look.')
    [void]$L.Add('')
    [void]$L.Add('| Chocolatey id | catalog | map |')
    [void]$L.Add('|---|---|---|')
    foreach ($C in $Conflicts) { [void]$L.Add("| $($C.id) | $($C.winget) | $($Build.Map[$C.id.ToLower()].winget) |") }
    [void]$L.Add('')
    [void]$L.Add('## Curated apps still without winget id')
    [void]$L.Add('')
    foreach ($C in @($Curated | Where-Object { -not $_.winget -and -not $Build.Map.Contains($_.id.ToLower()) })) {
        $Why = if ($Build.NoEquivalent.Contains($C.id.ToLower())) { $Build.NoEquivalent[$C.id.ToLower()] } elseif ($Build.Candidates.Contains($C.id.ToLower())) { 'candidates for review' } else { 'nothing found' }
        [void]$L.Add("- $($C.id) ($($C.name)): $Why")
    }
    [void]$L.Add('')
    [void]$L.Add('## Accepted')
    [void]$L.Add('')
    [void]$L.Add('| Chocolatey id | winget id | confidence | score | signals | note |')
    [void]$L.Add('|---|---|---|---|---|---|')
    foreach ($K in $Build.Map.Keys) { $E = $Build.Map[$K]; [void]$L.Add("| $K | $($E.winget) | $($E.confidence) | $($E.score) | $(@($E.signals) -join ', ') | $($E.note) |") }
    [void]$L.Add('')
    [void]$L.Add('## Candidates for review')
    [void]$L.Add('')
    [void]$L.Add('Not used by the app. Accept with an entry under "accept" in the review file, or reject under "reject".')
    [void]$L.Add('')
    [void]$L.Add('| Chocolatey id (title) | candidates (score, signals) |')
    [void]$L.Add('|---|---|')
    foreach ($K in $Build.Candidates.Keys) {
        $Text = (@($Build.Candidates[$K]) | ForEach-Object { "$($_.Id) ($($_.Score), $(@($_.Signals) -join '+'))" }) -join '; '
        [void]$L.Add("| $K ($($Titles[$K])) | $Text |")
    }
    [void]$L.Add('')
    [void]$L.Add('## No equivalent')
    [void]$L.Add('')
    [void]$L.Add('| Chocolatey id | reason |')
    [void]$L.Add('|---|---|')
    foreach ($K in $Build.NoEquivalent.Keys) { [void]$L.Add("| $K | $($Build.NoEquivalent[$K]) |") }
    foreach ($K in $Build.None.Keys) { [void]$L.Add("| $K | $($Build.None[$K]) (no candidate with score >= $($script:CandidateScore)) |") }
    [void]$L.Add('')
    return ($L -join "`n")
}
