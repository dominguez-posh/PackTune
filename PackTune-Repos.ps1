function Test-PackTuneRepoRecipeArguments {
    # Extra msiexec properties from a recipe are data that ends up in a device script: only simple PROPERTY=value pairs
    param([string]$Text)
    if (-not $Text) { return $true }
    return ($Text -cmatch '^(\s*[A-Z][A-Z0-9_]{0,40}=("[A-Za-z0-9 :\\._()-]{0,200}"|[A-Za-z0-9:\\._-]{0,200}))+\s*$')
}

function New-PackTuneRepoApp {
    <#
        Deploys an approved version of a repository app as a Win32 app (MSI: the existing MSI scripts; MSIX: the Win32 wrapper with
        the certificate of that version). Refused without approval of exactly the manifest in the repository, for an app that is in
        the tenant already, and when the files do not verify. The notes carry repo, commit and who approved. Returns the Intune app id.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$AppId, [Parameter(Mandatory = $true)][string]$Version,
        [ValidateSet("Available", "Required", "None")][string]$Assignment = $script:Settings.Assignment
    )
    Assert-PackTunePrerequisites
    Assert-PackTuneConnection
    Update-PackTuneToken
    $State = Assert-PackTuneRepoReady $Repository
    $Key = "$($State.Repository.Owner)/$($State.Repository.Repo)"
    $Index = Get-PackTuneRepoIndex -Repository $Key
    if ($Index.Damaged) { throw "The repository index is damaged: $($Index.Problems -join ' ')" }
    $Entry = Get-PackTuneRepoVersionEntry -Index $Index -AppId $AppId -Version $Version
    $Manifest = ([string]$Entry.Version.manifest).ToLower()
    if (-not (Test-PackTuneRepoApproved -Repository $Key -AppId $AppId -Version $Version -Manifest $Manifest)) { throw "$AppId $Version of $Key is not approved (or its manifest changed since): approve it first. Nothing was deployed." }
    $Approval = @(Get-PackTuneRepoApprovals | Where-Object { $_.Repository.ToLower() -eq $Key.ToLower() -and $_.AppId -eq $AppId -and $_.Version -eq $Version }) | Select-Object -First 1
    $Temp = Join-Path ([IO.Path]::GetTempPath()) ("packtune-repo-" + [guid]::NewGuid().ToString("N").Substring(0, 8))
    try {
        $Saved = Save-PackTuneRepoVersion -Repository $Key -AppId $AppId -Version $Version -Destination $Temp -ExpectedManifest $Manifest
        $Recipe = Get-Content -LiteralPath (Join-Path $Temp "recipe.json") -Raw | ConvertFrom-Json
        $By = ([string]$Approval.ApprovedBy) -replace '[^A-Za-z0-9._-]', ''
        if ($By.Length -gt 20) { $By = $By.Substring(0, 20) }
        $ExtraNotes = "repo=$Key;commit=$(([string]$Approval.Commit).Substring(0, 12));by=$By"
        $Existing = @(Get-PackTuneCustomApps)
        if ($Saved.Kind -eq "msi") {
            $Msi = [string]$Recipe.msi
            if ($Msi -notmatch '^[A-Za-z0-9][A-Za-z0-9._ -]{0,100}\.msi$') { throw "The recipe names an MSI file that is not allowed: '$Msi'." }
            $MsiPath = Join-Path $Saved.InstallerFolder $Msi
            if (-not (Test-Path -LiteralPath $MsiPath)) { throw "The installer files do not contain $Msi." }
            $Info = Get-PackTuneMsiInfo -Path $MsiPath
            if ((Get-PackTuneCustomAppId $Info) -ne $AppId) { throw "The MSI describes another product than the app id $AppId says: refused." }
            if ($Info.Version -ne $Version) { throw "The MSI has version $($Info.Version), the repository says ${Version}: refused." }
            if (-not (Test-PackTuneRepoRecipeArguments ([string]$Recipe.arguments))) { throw "The recipe has msiexec arguments that are not simple PROPERTY=value pairs: refused." }
            if (@($Existing | Where-Object { $_.ProductCode -eq $Info.ProductCode -or ($_.AppId -eq $AppId -and $_.Version -eq $Version) }).Count) { throw "$($Info.Name) $($Info.Version) is deployed already." }
            $Built = New-PackTuneCustomAppPackage -Info $Info -AppId $AppId -ExtraArguments ([string]$Recipe.arguments)
            $Icon = Get-PackTuneMsiIconBase64 -Info $Info
            $App = Add-PackTuneCustomIntuneApp -Info $Info -AppId $AppId -Built $Built -DisplayName $Info.Name -Publisher $Info.Manufacturer -IconBase64 $Icon -Manifest $Manifest -ExtraNotes $ExtraNotes
        }
        else {
            $MsixFile = Join-Path $Temp "package.msix"; $Cer = Join-Path $Temp "signing.cer"
            if (-not (Test-Path -LiteralPath $MsixFile) -or -not (Test-Path -LiteralPath $Cer)) { throw "An MSIX version needs package.msix and signing.cer." }
            $Identity = Get-PackTuneMsixIdentity -Path $MsixFile
            $Thumbprint = (New-Object Security.Cryptography.X509Certificates.X509Certificate2 $Cer).Thumbprint.ToUpper()
            $null = Assert-PackTuneSignedMsix -Path $MsixFile -PackageName ([string]$Identity.Name) -Publisher ([string]$Identity.Publisher) -Version ([string]$Identity.Version) -Thumbprint $Thumbprint
            if (@($Existing | Where-Object { $_.AppId -eq $AppId -and $_.Version -eq [string]$Identity.Version }).Count) { throw "$AppId $($Identity.Version) is deployed already." }
            $Build = [pscustomobject]@{ PackageName = [string]$Identity.Name; Version = [string]$Identity.Version; Thumbprint = $Thumbprint; Msix = $MsixFile; Cer = $Cer }
            $Package = New-PackTuneCustomMsixPackage -Build $Build -AppId $AppId
            $App = Add-PackTuneCustomMsixIntuneApp -Build $Build -AppId $AppId -Package $Package -DisplayName ([string]$Entry.App.name) -Publisher ([string]$Entry.App.publisher) -Manifest $Manifest -ExtraNotes $ExtraNotes
        }
        Set-PackTuneAssignment -Id $App.id -Assignment $Assignment
        Write-Host "Deployment of $($Entry.App.name) $Version from $Key was successful"
        return $App.id
    }
    finally { Remove-Item -LiteralPath $Temp -Recurse -Force -ErrorAction SilentlyContinue }
}

