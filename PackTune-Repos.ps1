function Get-PackTuneRepoBlobBase64([string]$Path) { [Convert]::ToBase64String([IO.File]::ReadAllBytes($Path)) }

function Write-PackTuneRepoVersion {
    <#
        One commit per version: the files of a downloaded store version (files over 90 MB go to a release named <app id>/<version>
        instead, same file name) plus the updated index, on the default branch through the git data API. Returns the commit sha.
    #>
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$Folder, [Parameter(Mandatory = $true)]$Manifest, [Parameter(Mandatory = $true)][string]$ManifestHash, $Recipe, [Parameter(Mandatory = $true)][string]$Token)
    $Found = Get-PackTuneRepository $Repository
    $Key = "$($Found.Owner)/$($Found.Repo)"
    $AppId = [string]$Manifest.app; $Version = [string]$Manifest.appVersion
    $Branch = $Found.DefaultBranch
    $Ref = (Invoke-PackTuneGitHubApi -Path "/repos/$Key/git/ref/heads/$Branch" -Token $Token).Body
    $Head = [string]$Ref.object.sha
    $BaseTree = [string](Invoke-PackTuneGitHubApi -Path "/repos/$Key/git/commits/$Head" -Token $Token).Body.tree.sha
    $Tree = New-Object System.Collections.ArrayList
    $AssetNames = New-Object System.Collections.ArrayList
    $Release = $null
    foreach ($File in @($Manifest.files) + [pscustomobject]@{ name = "manifest.json"; size = (Get-Item -LiteralPath (Join-Path $Folder "manifest.json")).Length }) {
        $Local = Join-Path $Folder ([string]$File.name)
        if ([string]$File.name -ne "manifest.json" -and (Get-Item -LiteralPath $Local).Length -gt $script:RepoAssetThreshold) {
            if ((Get-Item -LiteralPath $Local).Length -gt $script:RepoFileMaxBytes) { throw "$($File.name) is larger than 2 GB: it cannot be kept in a repository." }
            if (-not $Release) {
                $Tag = "$AppId/$Version"
                try { $Release = (Invoke-PackTuneGitHubApi -Path "/repos/$Key/releases/tags/$([uri]::EscapeDataString($AppId))/$([uri]::EscapeDataString($Version))" -Token $Token).Body }
                catch { if ($_.Exception.Data["Status"] -ne 404) { throw }; $Release = (Invoke-PackTuneGitHubApi -Method POST -Path "/repos/$Key/releases" -Token $Token -Body @{ tag_name = $Tag; target_commitish = $Branch; name = $Tag; draft = $false; prerelease = $false }).Body }
            }
            $Existing = @($Release.assets | Where-Object { $_.name -eq [string]$File.name }) | Select-Object -First 1
            if (-not $Existing -or [int64]$Existing.size -ne (Get-Item -LiteralPath $Local).Length) {
                $null = Invoke-PackTuneGitHubApi -Method POST -Absolute "https://uploads.github.com/repos/$Key/releases/$([int64]$Release.id)/assets?name=$([uri]::EscapeDataString([string]$File.name))" -Token $Token -InFile $Local
            }
            [void]$AssetNames.Add([string]$File.name)
            continue
        }
        $Blob = (Invoke-PackTuneGitHubApi -Method POST -Path "/repos/$Key/git/blobs" -Token $Token -Body @{ content = (Get-PackTuneRepoBlobBase64 $Local); encoding = "base64" }).Body
        [void]$Tree.Add(@{ path = "apps/$AppId/$Version/$($File.name)"; mode = "100644"; type = "blob"; sha = [string]$Blob.sha })
    }
    # the index: read the current one (or start a new one), add or replace this version
    $IndexFile = Join-Path $Folder "index.download"
    $Index = $null
    try { $null = Get-PackTuneRepoContent -Repository $Key -Segments @($script:RepoIndexName) -Destination $IndexFile -Token $Token; $Index = Get-Content -LiteralPath $IndexFile -Raw | ConvertFrom-Json }
    catch { if ($_.Exception.Data["Status"] -ne 404) { throw } }
    finally { Remove-Item -LiteralPath $IndexFile -Force -ErrorAction SilentlyContinue }
    $Apps = New-Object System.Collections.ArrayList
    $Entry = $null
    if ($Index) { foreach ($A in @($Index.apps)) { if ($A.id -eq $AppId) { $Entry = $A } else { [void]$Apps.Add($A) } } }
    $Versions = @(); if ($Entry) { $Versions = @($Entry.versions | Where-Object { [string]$_.version -ne $Version }) }
    $NewVersion = [ordered]@{ version = $Version; path = "apps/$AppId/$Version"; manifest = $ManifestHash; released = (Get-Date).ToString("yyyy-MM-dd") }
    if ($AssetNames.Count) { $NewVersion.assets = @($AssetNames) }
    $NewEntry = [ordered]@{ id = $AppId; name = $(if ($Recipe -and $Recipe.name) { [string]$Recipe.name } elseif ($Entry) { [string]$Entry.name } else { $AppId }); publisher = $(if ($Recipe -and $Recipe.publisher) { [string]$Recipe.publisher } elseif ($Entry) { [string]$Entry.publisher } else { "" }); kind = [string]$Manifest.kind; versions = @($Versions) + @($NewVersion) }
    [void]$Apps.Add($NewEntry)
    $NewIndex = [ordered]@{ format = 1; name = $(if ($Index -and $Index.name) { [string]$Index.name } else { $Found.Name }); apps = @($Apps | Sort-Object { [string]$_.id }) }
    $IndexJson = ConvertTo-Json -InputObject $NewIndex -Depth 8
    $IndexBlob = (Invoke-PackTuneGitHubApi -Method POST -Path "/repos/$Key/git/blobs" -Token $Token -Body @{ content = [Convert]::ToBase64String((New-Object Text.UTF8Encoding $false).GetBytes($IndexJson)); encoding = "base64" }).Body
    [void]$Tree.Add(@{ path = $script:RepoIndexName; mode = "100644"; type = "blob"; sha = [string]$IndexBlob.sha })
    $NewTree = (Invoke-PackTuneGitHubApi -Method POST -Path "/repos/$Key/git/trees" -Token $Token -Body @{ base_tree = $BaseTree; tree = @($Tree) }).Body
    $Name = if ($Recipe -and $Recipe.name) { [string]$Recipe.name } else { $AppId }
    $Commit = (Invoke-PackTuneGitHubApi -Method POST -Path "/repos/$Key/git/commits" -Token $Token -Body @{ message = "Add $Name $Version"; tree = [string]$NewTree.sha; parents = @($Head) }).Body
    $null = Invoke-PackTuneGitHubApi -Method PATCH -Path "/repos/$Key/git/refs/heads/$Branch" -Token $Token -Body @{ sha = [string]$Commit.sha; force = $false }
    return [string]$Commit.sha
}

function Move-PackTuneCustomAppToRepository {
    <#
        Move to repository: copies every version of a custom application from the SharePoint package store into a connected
        repository (own, write grant given), verifies everything by reading it back, switches the Intune notes (repo=, commit=) and
        keeps SharePoint. -ConfirmRemoval is called with the list of what would be removed from SharePoint; only when it returns $true
        is the store folder deleted (SharePoint keeps it in its recycle bin). Running it again continues: identical versions are skipped.
        Not offered when a stored version has no Intune app (nothing vouches for it).
    #>
    param([Parameter(Mandatory = $true)][string]$AppId, [Parameter(Mandatory = $true)][string]$Repository, [scriptblock]$ConfirmRemoval)
    Assert-PackTunePrerequisites
    Assert-PackTuneConnection
    Update-PackTuneToken
    $State = Assert-PackTuneRepoReady $Repository
    $Repo = $State.Repository
    $Key = "$($Repo.Owner)/$($Repo.Repo)"
    if ($Repo.ThirdParty) { throw "$Key is a third-party source: read only, not a target for Move." }
    $Token = Get-PackTuneRepoToken $Key -Write
    if (-not $Token) { throw "Moving needs the write grant (Contents: write) for ${Key}: grant it in a separate step first (Grant-PackTuneRepoWrite)." }
    if (-not $State.Info.permissions -or -not $State.Info.permissions.push) {
        $Info = (Invoke-PackTuneGitHubApi -Path "/repos/$Key" -Token $Token).Body
        if (-not $Info.permissions.push) { throw "The token for $Key can not write." }
    }
    $Store = Get-PackTuneStoreState
    if ($Store.State -ne "Ready") { throw "The package store is not ready: $($Store.Message)" }
    $Stored = @(Get-PackTuneStoreVersions -AppId $AppId -Store $Store.Store)
    if (-not $Stored.Count) { throw "$AppId has no versions in the package store." }
    $Incomplete = @($Stored | Where-Object { -not $_.Complete })
    if ($Incomplete.Count) { throw "Version(s) $((($Incomplete).Version) -join ', ') of $AppId are incomplete in the store (no manifest). Decide what to do with them first; nothing was moved." }
    $Tenant = @(Get-PackTuneCustomApps | Where-Object { $_.AppId -eq $AppId })
    foreach ($V in $Stored) { if (-not @($Tenant | Where-Object { $_.Version -eq $V.Version -and $_.Manifest.Length -eq 64 }).Count) { throw "Version $($V.Version) of $AppId has no Intune app with a full manifest anchor: nothing vouches for it, so it is not moved (see Get-PackTuneCustomAnchorReport)." } }
    $Existing = $null; try { $Existing = Get-PackTuneRepoIndex -Repository $Key -Refresh } catch { }
    $Result = [ordered]@{ AppId = $AppId; Repository = $Key; Copied = @(); Skipped = @(); Verified = @(); Switched = @(); RemovedFromStore = $false; Commits = @{} }
    $Work = Join-Path ([IO.Path]::GetTempPath()) ("packtune-move-" + [guid]::NewGuid().ToString("N").Substring(0, 8))
    try {
        foreach ($V in @($Stored | Sort-Object { try { [version]$_.Version } catch { [version]"0.0" } })) {
            $Anchor = ([string](@($Tenant | Where-Object { $_.Version -eq $V.Version })[0].Manifest)).ToLower()
            $Folder = Join-Path $Work $V.Version
            $Local = Save-PackTuneStoreVersion -AppId $AppId -Version $V.Version -Destination $Folder -ExpectedManifest $Anchor -Store $Store.Store
            $Manifest = Get-Content -LiteralPath (Join-Path $Folder "manifest.json") -Raw | ConvertFrom-Json
            $Recipe = $null; $RecipeFile = Join-Path $Folder "recipe.json"; if (Test-Path -LiteralPath $RecipeFile) { $Recipe = Get-Content -LiteralPath $RecipeFile -Raw | ConvertFrom-Json }
            $Done = $false
            if ($Existing -and -not $Existing.Damaged) { $Done = [bool](@($Existing.Apps | Where-Object { $_.id -eq $AppId } | ForEach-Object { $_.versions } | Where-Object { [string]$_.version -eq $V.Version -and ([string]$_.manifest).ToLower() -eq $Anchor }).Count) }
            if ($Done) { $Result.Skipped += $V.Version }
            else { $Result.Commits[$V.Version] = Write-PackTuneRepoVersion -Repository $Key -Folder $Folder -Manifest $Manifest -ManifestHash $Anchor -Recipe $Recipe -Token $Token; $Result.Copied += $V.Version }
        }
        # verify: read everything back from the repository against the manifests of the store
        foreach ($V in $Stored) {
            $Anchor = ([string](@($Tenant | Where-Object { $_.Version -eq $V.Version })[0].Manifest)).ToLower()
            $Back = Join-Path $Work ("verify-" + $V.Version)
            $null = Save-PackTuneRepoVersion -Repository $Key -AppId $AppId -Version $V.Version -Destination $Back -ExpectedManifest $Anchor
            $Result.Verified += $V.Version
        }
        # switch: the notes keep the manifest anchor and get repo= and commit=
        foreach ($T in $Tenant) {
            $Sha = if ($Result.Commits.ContainsKey($T.Version)) { $Result.Commits[$T.Version] } else { [string](Get-PackTuneRepoCommitInfo -Repository $Key -Path "apps/$AppId/$($T.Version)").Sha }
            $App = Invoke-IntuneModule { Get-IntuneWin32App -ID $T.Id }
            $Notes = [string]$App.notes
            if ($Notes -notmatch '(?:^|;)repo=') {
                $New = "$Notes;repo=$Key;commit=$($Sha.Substring(0, 12))"
                if ($New.Length -lt $script:NotesMaxLength) { Invoke-IntuneModule { Set-IntuneWin32App -ID $T.Id -Notes $New } | Out-Null; $Result.Switched += $T.Version }
            }
        }
        # remove from SharePoint only after an explicit confirmation of what is removed
        if ($ConfirmRemoval) {
            $Plan = [pscustomobject]@{ AppId = $AppId; Versions = @($Stored.Version); Where = "package store (SharePoint recycle bin keeps it 93 days)"; Repository = $Key }
            if ([bool](& $ConfirmRemoval $Plan)) { Remove-PackTuneStoreApp -AppId $AppId -Store $Store.Store; $Result.RemovedFromStore = $true }
        }
    }
    finally { Remove-Item -LiteralPath $Work -Recurse -Force -ErrorAction SilentlyContinue }
    return [pscustomobject]$Result
}

