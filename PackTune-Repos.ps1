<#
    Custom repositories on GitHub (docs\plans\custom-repositories.md): any number of repositories as sources of custom
    applications next to the SharePoint package store. A repository holds apps in the layout and manifest format of the
    store plus an index file:

        packtune.json                                     index (a convenience; nothing in it is trusted)
        apps/<app id>/<version>/  package.intunewin | package.msix | installer.zip | recipe.json | signing.cer |
                                  documentation.zip | manifest.json (SHA256 of every file)
        Large files (over 90 MB) are assets of a release named <app id>/<version> (same file name, same manifest).

    Trust model (fail closed):
      - repositories are pinned by owner/name and the numeric repository id; rename, transfer and fork changes need a confirmation
      - every file is checked against the manifest, the manifest against the index and, once approved, against the approval
      - a new version (or a changed manifest) is not deployable until a person approved it; approvals are recorded locally and in the Intune notes
      - nothing from a repository is executed on the admin PC; recipes are data and device scripts are generated by PackTune
      - tokens: DPAPI per Windows user, never in settings, notes, logs or error messages; read and write grants are separate

    All requests go through Invoke-PackTuneGitHub (replaceable: the checks use a fake GitHub in memory).
    Loaded by PackTune-Main.ps1.
#>

$script:GitHubApi = "https://api.github.com"
$script:GitHubHosts = @("api.github.com", "uploads.github.com", "github.com", "objects.githubusercontent.com", "release-assets.githubusercontent.com", "raw.githubusercontent.com")
$script:RepoIndexName = "packtune.json"
$script:RepoIndexMaxBytes = 1MB
$script:RepoManifestMaxBytes = 256KB
$script:RepoAssetThreshold = 90MB
$script:RepoFileMaxBytes = 2GB
$script:RepoName = '^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$'
$script:RepoOwner = '^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$'
$script:GitHubBudget = $null
$script:RepoSecretsInMemory = New-Object System.Collections.ArrayList

#region transport

function Test-PackTuneGitHubUrl {
    # Only https to the allow-listed GitHub hosts
    param([string]$Url)
    try { $Uri = [Uri]$Url } catch { return $false }
    return ($Uri.Scheme -eq "https" -and $Uri.Host.ToLower() -in $script:GitHubHosts)
}

function Wait-PackTuneGitHub([int]$Seconds) { Start-Sleep -Seconds $Seconds }

function Protect-PackTuneGitHubText {
    # Removes every token this session handled from a text (messages, logs): tokens never appear in output
    param([string]$Text)
    foreach ($Secret in @($script:RepoSecretsInMemory)) { if ($Secret -and $Text) { $Text = $Text.Replace([string]$Secret, "***") } }
    return $Text -replace '(github_pat_|ghp_|gho_|ghu_|ghs_)[A-Za-z0-9_]{10,}', '***'
}

function Invoke-PackTuneGitHub {
    <#
        One HTTPS request to GitHub. Returns Status, Body (parsed JSON or $null) and Headers (lower-case names); HTTP errors
        come back as a status, network errors are thrown. Redirects are followed by hand: only to allow-listed hosts and
        never with the token to another host. Replaceable: the checks use a fake.
    #>
    param(
        [string]$Method = "GET", [string]$Path, [string]$Absolute, [string]$Token, $Body, [byte[]]$Bytes, [string]$InFile, [string]$OutFile,
        [string]$Accept = "application/vnd.github+json", [string]$IfNoneMatch, [string]$ContentType
    )
    $Url = if ($Absolute) { $Absolute } else { "$($script:GitHubApi)$Path" }
    for ($Hop = 0; $Hop -lt 5; $Hop++) {
        if (-not (Test-PackTuneGitHubUrl $Url)) { throw "Refused: $Url is not an https address of GitHub." }
        $Request = [Net.HttpWebRequest]::Create($Url)
        $Request.Method = $Method
        $Request.AllowAutoRedirect = $false
        $Request.UserAgent = "PackTune"
        $Request.Accept = $Accept
        $Request.Timeout = 120000
        $Request.ReadWriteTimeout = 600000
        $Request.AllowWriteStreamBuffering = $false
        $Request.Headers["X-GitHub-Api-Version"] = "2022-11-28"
        $SameHost = ([Uri]$Url).Host -in "api.github.com", "uploads.github.com"
        if ($Token -and $SameHost) { $Request.Headers["Authorization"] = "Bearer $Token" }
        if ($IfNoneMatch) { $Request.Headers["If-None-Match"] = $IfNoneMatch }
        $Payload = $null
        if ($null -ne $Body) { $Payload = [Text.Encoding]::UTF8.GetBytes(($Body | ConvertTo-Json -Depth 8 -Compress)); $Request.ContentType = "application/json" }
        elseif ($Bytes) { $Payload = $Bytes; $Request.ContentType = $(if ($ContentType) { $ContentType } else { "application/octet-stream" }) }
        $Length = if ($InFile) { (Get-Item -LiteralPath $InFile).Length } elseif ($Payload) { $Payload.Length } else { 0 }
        if ($Method -in "POST", "PUT", "PATCH") { $Request.ContentLength = $Length; if ($InFile) { $Request.ContentType = $(if ($ContentType) { $ContentType } else { "application/octet-stream" }) } }
        try {
            if ($Method -in "POST", "PUT", "PATCH" -and $Length -gt 0) {
                $Out = $Request.GetRequestStream()
                try {
                    if ($InFile) { $In = [IO.File]::OpenRead($InFile); try { $In.CopyTo($Out, 81920) } finally { $In.Dispose() } } else { $Out.Write($Payload, 0, $Payload.Length) }
                }
                finally { $Out.Dispose() }
            }
            $Response = $Request.GetResponse()
        }
        catch [Net.WebException] {
            $Response = $_.Exception.Response
            if (-not $Response) { throw (Protect-PackTuneGitHubText "GitHub could not be reached: $($_.Exception.Message)") }
        }
        try {
            $Status = [int]$Response.StatusCode
            $Headers = @{}
            foreach ($Name in $Response.Headers.AllKeys) { $Headers[$Name.ToLower()] = [string]$Response.Headers[$Name] }
            if ($Status -in 301, 302, 303, 307, 308 -and $Headers["location"]) {
                $Url = [string]$Headers["location"]
                if ($Status -in 301, 302, 303 -and $Method -ne "GET") { $Method = "GET" }
                continue
            }
            $Stream = $Response.GetResponseStream()
            try {
                if ($OutFile -and $Status -in 200, 201) {
                    $File = [IO.File]::Create($OutFile)
                    try { $Stream.CopyTo($File, 81920) } finally { $File.Dispose() }
                    return [pscustomobject]@{ Status = $Status; Body = $null; Headers = $Headers }
                }
                $Reader = New-Object IO.StreamReader($Stream, [Text.Encoding]::UTF8)
                $Text = $Reader.ReadToEnd()
            }
            finally { $Stream.Dispose() }
            $Json = $null
            if ($Text -and $Headers["content-type"] -like "*json*") { try { $Json = $Text | ConvertFrom-Json } catch { } }
            return [pscustomobject]@{ Status = $Status; Body = $Json; Headers = $Headers }
        }
        finally { $Response.Close() }
    }
    throw "GitHub redirected too often."
}

function Invoke-PackTuneGitHubApi {
    <#
        Invoke-PackTuneGitHub with rate-limit handling and readable errors. 304 and 2xx return the response. A used-up limit
        or a 429 waits for Retry-After (at most 2 minutes, three tries) and then says clearly what happened.
    #>
    param(
        [string]$Method = "GET", [string]$Path, [string]$Absolute, [string]$Token, $Body, [byte[]]$Bytes, [string]$InFile, [string]$OutFile,
        [string]$Accept = "application/vnd.github+json", [string]$IfNoneMatch, [string]$ContentType
    )
    if ($Token -and $Token -notin @($script:RepoSecretsInMemory)) { [void]$script:RepoSecretsInMemory.Add($Token) }
    $Arguments = @{ Method = $Method; Accept = $Accept }
    foreach ($Key in "Path", "Absolute", "Token", "InFile", "OutFile", "IfNoneMatch", "ContentType") { if ((Get-Variable $Key).Value) { $Arguments[$Key] = (Get-Variable $Key).Value } }
    if ($null -ne $Body) { $Arguments.Body = $Body }
    if ($Bytes) { $Arguments.Bytes = $Bytes }
    for ($Try = 1; $Try -le 3; $Try++) {
        $Response = Invoke-PackTuneGitHub @Arguments
        $Headers = $Response.Headers
        if ($Headers -and $Headers["x-ratelimit-remaining"]) {
            $script:GitHubBudget = [pscustomobject]@{ Remaining = [int]$Headers["x-ratelimit-remaining"]; Limit = [int]$Headers["x-ratelimit-limit"]; Reset = $Headers["x-ratelimit-reset"]; Authenticated = [bool]$Token }
        }
        if ($Response.Status -lt 400) { return $Response }
        $Detail = $null; try { $Detail = [string]$Response.Body.message } catch { }
        $Limited = $Response.Status -eq 429 -or ($Response.Status -eq 403 -and ($Headers["x-ratelimit-remaining"] -eq "0" -or $Headers["retry-after"] -or $Detail -like "*rate limit*"))
        if ($Limited) {
            $Seconds = 0
            if ($Headers["retry-after"]) { $Seconds = [int]$Headers["retry-after"] }
            elseif ($Headers["x-ratelimit-reset"]) { $Seconds = [Math]::Max(1, [int]([int64]$Headers["x-ratelimit-reset"] - [DateTimeOffset]::UtcNow.ToUnixTimeSeconds())) }
            if ($Try -lt 3 -and $Seconds -gt 0 -and $Seconds -le 120) { Wait-PackTuneGitHub $Seconds; continue }
            $Hint = if (-not $Token) { " Without a sign-in GitHub allows only 60 requests per hour; add a token for this repository to get 5,000." } else { "" }
            throw (Protect-PackTuneGitHubText "GitHub's rate limit is used up (resets in about $Seconds seconds).$Hint")
        }
        $Cause = switch ($Response.Status) {
            401 { "GitHub rejected the token (expired or revoked). Sign in to the repository again." }
            403 { "GitHub refused access (403)$(if ($Detail) { ": $Detail" }). A token may need Contents permission, or SSO authorization for the organization." }
            404 { "Not found, or no access: a private repository needs a token with Contents (read) permission." }
            422 { "GitHub did not accept the request (422)$(if ($Detail) { ": $Detail" })." }
            default { "GitHub answered $($Response.Status)$(if ($Detail) { ": $Detail" })." }
        }
        $Failure = New-Object System.Exception (Protect-PackTuneGitHubText "$Method $Path`: $Cause")
        $Failure.Data["Status"] = $Response.Status
        throw $Failure
    }
}

