function Get-PackTuneRepoAsset {
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$AppId, [Parameter(Mandatory = $true)][string]$Version, [Parameter(Mandatory = $true)][string]$Name, [Parameter(Mandatory = $true)][string]$Destination)
    $Found = Get-PackTuneRepository $Repository
    $Key = "$($Found.Owner)/$($Found.Repo)"
    $Token = Get-PackTuneRepoToken $Key
    $Release = (Invoke-PackTuneGitHubApi -Path "/repos/$Key/releases/tags/$([uri]::EscapeDataString($AppId))/$([uri]::EscapeDataString($Version))" -Token $Token).Body
    $Asset = @($Release.assets | Where-Object { $_.name -eq $Name }) | Select-Object -First 1
    if (-not $Asset) { throw "The release of $AppId $Version has no asset $Name." }
    $null = Invoke-PackTuneGitHubApi -Path "/repos/$Key/releases/assets/$([int64]$Asset.id)" -Token $Token -Accept "application/octet-stream" -OutFile $Destination
}

function Save-PackTuneRepoVersion {
    <#
        Downloads one version into -Destination and verifies it. -ExpectedManifest is required (fail closed): the SHA256 that was
        approved, or the one in the Intune notes. The manifest must match it and the index; every file must match the manifest
        (size and SHA256). installer.zip is unpacked into <Destination>\installer (zip-slip safe) only after everything matched.
    #>
    param(
        [Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$AppId, [Parameter(Mandatory = $true)][string]$Version,
        [Parameter(Mandatory = $true)][string]$Destination, [AllowEmptyString()][string]$ExpectedManifest
    )
    $Anchor = ([string]$ExpectedManifest).Trim().ToLower()
    if ($Anchor -notmatch '^[0-9a-f]{64}$') { throw "No approved manifest hash was given for $AppId ${Version}: nothing was downloaded." }
    $State = Assert-PackTuneRepoReady $Repository
    $Key = "$($State.Repository.Owner)/$($State.Repository.Repo)"
    $Index = Get-PackTuneRepoIndex -Repository $Key
    if ($Index.Damaged) { throw "The repository index is damaged: $($Index.Problems -join ' ')" }
    if ($Index.Stale) { throw "GitHub could not be reached; the repository list is stale. Nothing is deployed from a stale repository." }
    $Entry = Get-PackTuneRepoVersionEntry -Index $Index -AppId $AppId -Version $Version
    if (([string]$Entry.Version.manifest).ToLower() -ne $Anchor) { throw "The manifest of $AppId $Version in the repository is not the one that was approved. The version needs a new approval; nothing was downloaded." }
    New-Item -ItemType Directory -Path $Destination -Force | Out-Null
    $Read = Read-PackTuneRepoManifest -Repository $Key -AppId $AppId -Version $Version -Destination (Join-Path $Destination "manifest.json") -IndexManifest $Anchor
    $AssetNames = @($Entry.Version.assets | Where-Object { $_ } | ForEach-Object { [string]$_ })
    $Saved = New-Object System.Collections.ArrayList
    foreach ($File in @($Read.Manifest.files)) {
        $Target = Join-Path $Destination ([string]$File.name)
        if ([string]$File.name -in $AssetNames) { Get-PackTuneRepoAsset -Repository $Key -AppId $AppId -Version $Version -Name ([string]$File.name) -Destination $Target }
        else { $null = Get-PackTuneRepoContent -Repository $Key -Segments @("apps", $AppId, $Version, [string]$File.name) -Destination $Target }
        if ((Get-Item -LiteralPath $Target).Length -ne [int64]$File.size) { throw "$($File.name) has another size than the manifest says: the repository was changed. Nothing was unpacked." }
        if ((Get-FileHash -LiteralPath $Target -Algorithm SHA256).Hash.ToLower() -ne ([string]$File.sha256).ToLower()) { throw "$($File.name) does not match the manifest (SHA256): the file in the repository was changed. Nothing was unpacked." }
        [void]$Saved.Add($Target)
    }
    $Installer = $null
    $Zip = Join-Path $Destination "installer.zip"
    if (Test-Path -LiteralPath $Zip) { $Installer = Join-Path $Destination "installer"; Expand-PackTuneZip -Path $Zip -Destination $Installer }
    [pscustomobject]@{ AppId = $AppId; Version = $Version; Destination = $Destination; Files = @($Saved); InstallerFolder = $Installer; ManifestHash = $Read.Hash; Kind = [string]$Read.Manifest.kind; Repository = $Key }
}

