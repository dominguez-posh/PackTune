#region state, index, listing

function Get-PackTuneRepoState {
    <#
        Ready | NeedsConfirmation (renamed or fork status changed) | Mismatch (the name now belongs to another repository: refused) |
        NoAccess. Pinned identity: owner/name and repository id.
    #>
    param([Parameter(Mandatory = $true)][string]$Repository)
    $Found = Get-PackTuneRepository $Repository
    $Token = Get-PackTuneRepoToken "$($Found.Owner)/$($Found.Repo)"
    try { $Info = (Invoke-PackTuneGitHubApi -Path "/repos/$($Found.Owner)/$($Found.Repo)" -Token $Token).Body }
    catch { return [pscustomobject]@{ State = "NoAccess"; Message = $_.Exception.Message; Repository = $Found; Info = $null } }
    if ([int64]$Info.id -ne [int64]$Found.RepoId) {
        return [pscustomobject]@{ State = "Mismatch"; Message = "$($Found.Owner)/$($Found.Repo) is another repository now (id $($Info.id), pinned $($Found.RepoId)). Nothing is read from it."; Repository = $Found; Info = $Info }
    }
    if (([string]$Info.full_name).ToLower() -ne "$($Found.Owner)/$($Found.Repo)".ToLower() -or [bool]$Info.fork -ne [bool]$Found.Fork -or [bool]$Info.private -ne [bool]$Found.Private) {
        return [pscustomobject]@{ State = "NeedsConfirmation"; Message = "The repository changed: now $($Info.full_name) (fork: $($Info.fork), private: $($Info.private)); pinned $($Found.Owner)/$($Found.Repo). Confirm the new identity to continue."; Repository = $Found; Info = $Info }
    }
    return [pscustomobject]@{ State = "Ready"; Message = ""; Repository = $Found; Info = $Info }
}

function Confirm-PackTuneRepositoryIdentity {
    # The person accepts the new name (same repository id). A different id is never accepted.
    param([Parameter(Mandatory = $true)][string]$Repository)
    $State = Get-PackTuneRepoState $Repository
    if ($State.State -ne "NeedsConfirmation") { throw "Nothing to confirm: $($State.State) $($State.Message)" }
    $Info = $State.Info
    $List = foreach ($Item in Get-PackTuneRepositories) {
        if ([int64]$Item.RepoId -eq [int64]$Info.id) { $Item.Owner = [string]$Info.owner.login; $Item.Repo = [string]$Info.name; $Item.Fork = [bool]$Info.fork; $Item.Private = [bool]$Info.private; $Item.DefaultBranch = [string]$Info.default_branch }
        $Item
    }
    Save-PackTuneRepositories $List
}

function Assert-PackTuneRepoReady {
    param([Parameter(Mandatory = $true)][string]$Repository)
    $State = Get-PackTuneRepoState $Repository
    if ($State.State -ne "Ready") { throw "$($State.State): $($State.Message)" }
    return $State
}

function Get-PackTuneRepoWarnings {
    # Readable hints about a repository: unprotected default branch (when GitHub shows it), public third-party source
    param([Parameter(Mandatory = $true)][string]$Repository)
    $Found = Get-PackTuneRepository $Repository
    $Warnings = @()
    if ($Found.ThirdParty) { $Warnings += "Third-party source: anyone who controls it controls what you can deploy. Every version needs your approval." }
    try {
        $Branch = (Invoke-PackTuneGitHubApi -Path "/repos/$($Found.Owner)/$($Found.Repo)/branches/$($Found.DefaultBranch)" -Token (Get-PackTuneRepoToken "$($Found.Owner)/$($Found.Repo)")).Body
        if (-not [bool]$Branch.protected) { $Warnings += "The default branch '$($Found.DefaultBranch)' is not protected: require pull requests and block force pushes." }
    }
    catch { }
    return $Warnings
}

function Test-PackTuneRepoIndex {
    # Schema checks of an index; returns the problems (empty = fine)
    param($Index)
    $Problems = New-Object System.Collections.ArrayList
    if (-not $Index -or $Index.format -ne 1) { [void]$Problems.Add("The index has no format 1."); return @($Problems) }
    $Seen = @{}
    foreach ($App in @($Index.apps)) {
        $Id = [string]$App.id
        if ($Id -notmatch $script:StoreSegment) { [void]$Problems.Add("App id '$Id' is not valid."); continue }
        if ($Seen[$Id]) { [void]$Problems.Add("App id '$Id' is listed twice."); continue }
        $Seen[$Id] = $true
        if ([string]$App.kind -notin "msi", "msix") { [void]$Problems.Add("App '$Id' has an unknown kind '$($App.kind)'.") }
        $Versions = @{}
        foreach ($V in @($App.versions)) {
            $Version = [string]$V.version
            if ($Version -notmatch $script:StoreSegment) { [void]$Problems.Add("Version '$Version' of $Id is not valid."); continue }
            if ($Versions[$Version]) { [void]$Problems.Add("Version $Version of $Id is listed twice."); continue }
            $Versions[$Version] = $true
            if ([string]$V.path -cne "apps/$Id/$Version") { [void]$Problems.Add("The path of $Id $Version must be apps/$Id/$Version.") }
            if ([string]$V.manifest -notmatch '^[0-9a-fA-F]{64}$') { [void]$Problems.Add("$Id $Version has no manifest hash.") }
            foreach ($Asset in @($V.assets)) { if ($Asset -and [string]$Asset -notin $script:StoreFileNames) { [void]$Problems.Add("$Id $Version names an asset '$Asset' that is not a package file.") } }
        }
    }
    return @($Problems)
}

function Get-PackTuneRepoContent {
    # One file of the repository by path (segments checked), to a local file. Verification is the caller's job.
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string[]]$Segments, [Parameter(Mandatory = $true)][string]$Destination, [string]$IfNoneMatch, [string]$Token)
    $Found = Get-PackTuneRepository $Repository
    foreach ($S in $Segments) { if ($S -notmatch '^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$' -or $S -match '\.\.') { throw "Path segment '$S' is not allowed." } }
    $Path = ($Segments | ForEach-Object { [uri]::EscapeDataString($_) }) -join "/"
    if (-not $Token) { $Token = Get-PackTuneRepoToken "$($Found.Owner)/$($Found.Repo)" }
    Invoke-PackTuneGitHubApi -Path "/repos/$($Found.Owner)/$($Found.Repo)/contents/${Path}?ref=$([uri]::EscapeDataString($Found.DefaultBranch))" -Token $Token -Accept "application/vnd.github.raw" -OutFile $Destination -IfNoneMatch $IfNoneMatch
}

function Get-PackTuneRepoIndex {
    <#
        The index of a repository (ETag-cached; a failed request returns the last known index as Stale). Damaged = schema problems:
        a damaged repository cannot be deployed from. The index is a listing only; manifests carry the trust.
    #>
    param([Parameter(Mandatory = $true)][string]$Repository, [switch]$Refresh)
    $Found = Get-PackTuneRepository $Repository
    $Key = "$($Found.Owner)/$($Found.Repo)"
    $Cache = Get-PackTuneRepoPath ("repos\" + $Key.Replace("/", "__"))
    New-Item -ItemType Directory -Path $Cache -Force | Out-Null
    $IndexFile = Join-Path $Cache "index.json"
    $EtagFile = Join-Path $Cache "index.etag"
    $Etag = if (-not $Refresh -and (Test-Path -LiteralPath $EtagFile) -and (Test-Path -LiteralPath $IndexFile)) { (Get-Content -LiteralPath $EtagFile -Raw).Trim() } else { $null }
    $Stale = $false
    $Temp = Join-Path $Cache ("download-" + [guid]::NewGuid().ToString("N"))
    try {
        try {
            $Response = Get-PackTuneRepoContent -Repository $Key -Segments @($script:RepoIndexName) -Destination $Temp -IfNoneMatch $Etag
            if ($Response.Status -eq 200) {
                if ((Get-Item -LiteralPath $Temp).Length -gt $script:RepoIndexMaxBytes) { throw "The index is larger than $($script:RepoIndexMaxBytes / 1KB) KB: refused." }
                Move-Item -LiteralPath $Temp -Destination $IndexFile -Force
                if ($Response.Headers["etag"]) { Set-Content -LiteralPath $EtagFile -Value $Response.Headers["etag"] -Encoding ASCII }
            }
        }
        catch {
            if ($_.Exception.Data["Status"] -eq 404) { return [pscustomobject]@{ Repository = $Found; Apps = @(); Damaged = $true; Problems = @("The repository has no $($script:RepoIndexName) at its root."); Stale = $false; Name = $null } }
            if (-not (Test-Path -LiteralPath $IndexFile)) { throw }
            $Stale = $true
        }
    }
    finally { Remove-Item -LiteralPath $Temp -Force -ErrorAction SilentlyContinue }
    try { $Index = Get-Content -LiteralPath $IndexFile -Raw | ConvertFrom-Json } catch { return [pscustomobject]@{ Repository = $Found; Apps = @(); Damaged = $true; Problems = @("The index is not valid JSON."); Stale = $Stale; Name = $null } }
    $Problems = @(Test-PackTuneRepoIndex $Index)
    [pscustomobject]@{ Repository = $Found; Apps = @($(if ($Problems.Count) { @() } else { @($Index.apps) })); Damaged = ($Problems.Count -gt 0); Problems = $Problems; Stale = $Stale; Name = [string]$Index.name }
}

function Get-PackTuneRepositoryApps {
    <# One row per app of one repository (source label "Repository: <name>"), with the approval state of its newest version. #>
    param([Parameter(Mandatory = $true)][string]$Repository, [switch]$Refresh)
    $State = Assert-PackTuneRepoReady $Repository
    $Index = Get-PackTuneRepoIndex -Repository $Repository -Refresh:$Refresh
    if ($Index.Damaged) { throw "The repository index is damaged: $($Index.Problems -join ' ')" }
    $Repo = $State.Repository
    foreach ($App in $Index.Apps) {
        $Versions = @($App.versions | Sort-Object { try { [version]([string]$_.version) } catch { [version]"0.0" } } -Descending)
        $Latest = $Versions | Select-Object -First 1
        [pscustomobject]@{
            Source = (Get-PackTuneRepoLabel $Repo); Repository = "$($Repo.Owner)/$($Repo.Repo)"; Private = $Repo.Private; ThirdParty = $Repo.ThirdParty; Stale = $Index.Stale
            AppId = [string]$App.id; Name = [string]$App.name; Publisher = [string]$App.publisher; Kind = [string]$App.kind
            Versions = @($Versions | ForEach-Object { [string]$_.version }); Latest = [string]$Latest.version
            Approved = (Test-PackTuneRepoApproved -Repository "$($Repo.Owner)/$($Repo.Repo)" -AppId ([string]$App.id) -Version ([string]$Latest.version) -Manifest ([string]$Latest.manifest))
        }
    }
}

