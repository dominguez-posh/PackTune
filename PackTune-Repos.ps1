function Get-PackTuneRepoPath([string]$Name) { Join-Path $script:WorkRoot $Name }

function ConvertTo-PackTuneRepoKey {
    # "owner/name" or a github.com URL -> "owner/name"; anything else is refused
    param([Parameter(Mandatory = $true)][string]$Text)
    $Clean = $Text.Trim()
    if ($Clean -match '^https://github\.com/([^/]+)/([^/]+?)(?:\.git)?/?$') { $Clean = "$($Matches[1])/$($Matches[2])" }
    if ($Clean -notmatch '^([^/]+)/([^/]+)$') { throw "A repository is written owner/name or https://github.com/owner/name" }
    $Owner = $Matches[1]; $Name = $Matches[2]
    if ($Owner -notmatch $script:RepoOwner -or $Name -notmatch $script:RepoName -or $Name -in ".", "..") { throw "'$Clean' is not a valid GitHub repository name" }
    return "$Owner/$Name"
}

function Get-PackTuneRepositories {
    $File = Get-PackTuneRepoPath "repositories.json"
    if (-not (Test-Path -LiteralPath $File)) { return @() }
    try { return @((Get-Content -LiteralPath $File -Raw | ConvertFrom-Json) | Where-Object { $_ }) } catch { return @() }
}

function Save-PackTuneRepositories($List) {
    New-Item -ItemType Directory -Path $script:WorkRoot -Force | Out-Null
    ConvertTo-Json -InputObject @($List) -Depth 5 | Set-Content -LiteralPath (Get-PackTuneRepoPath "repositories.json") -Encoding UTF8
}

function Get-PackTuneRepository {
    param([Parameter(Mandatory = $true)][string]$Repository)
    $Key = (ConvertTo-PackTuneRepoKey $Repository).ToLower()
    $Found = @(Get-PackTuneRepositories | Where-Object { "$($_.Owner)/$($_.Repo)".ToLower() -eq $Key }) | Select-Object -First 1
    if (-not $Found) { throw "The repository $Repository is not connected." }
    return $Found
}

function Get-PackTuneRepoLabel($Repo) { "Repository: $($Repo.Name)" }

function Set-PackTuneRepoToken {
    <# DPAPI-protected (this Windows user on this computer), never in the settings file. -Write is the separate write grant. #>
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$Token, [switch]$Write)
    $Key = (ConvertTo-PackTuneRepoKey $Repository).ToLower()
    [void]$script:RepoSecretsInMemory.Add($Token)
    $File = Get-PackTuneRepoPath "repo-tokens.json"
    $Data = @{}
    if (Test-Path -LiteralPath $File) { try { (Get-Content -LiteralPath $File -Raw | ConvertFrom-Json).PSObject.Properties | ForEach-Object { $Data[$_.Name] = $_.Value } } catch { } }
    $Slot = @{}
    if ($Data[$Key]) { $Data[$Key].PSObject.Properties | ForEach-Object { $Slot[$_.Name] = $_.Value } }
    $Slot[$(if ($Write) { "write" } else { "read" })] = (ConvertFrom-SecureString (ConvertTo-SecureString -String $Token -AsPlainText -Force))
    $Data[$Key] = $Slot
    New-Item -ItemType Directory -Path $script:WorkRoot -Force | Out-Null
    ConvertTo-Json -InputObject $Data -Depth 4 | Set-Content -LiteralPath $File -Encoding UTF8
}

function Get-PackTuneRepoToken {
    # The plain token for one call (or $null); the write grant only when asked for
    param([Parameter(Mandatory = $true)][string]$Repository, [switch]$Write)
    $Key = (ConvertTo-PackTuneRepoKey $Repository).ToLower()
    $File = Get-PackTuneRepoPath "repo-tokens.json"
    if (-not (Test-Path -LiteralPath $File)) { return $null }
    try { $Data = Get-Content -LiteralPath $File -Raw | ConvertFrom-Json } catch { return $null }
    $Slot = $Data.$Key
    if (-not $Slot) { return $null }
    $Cipher = if ($Write) { $Slot.write } else { if ($Slot.read) { $Slot.read } else { $null } }
    if (-not $Cipher) { return $null }
    try {
        $Secure = ConvertTo-SecureString -String $Cipher
        $Pointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($Secure)
        try { $Token = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($Pointer) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($Pointer) }
        if ($Token -notin @($script:RepoSecretsInMemory)) { [void]$script:RepoSecretsInMemory.Add($Token) }
        return $Token
    }
    catch { return $null }
}

function Remove-PackTuneRepoToken {
    param([Parameter(Mandatory = $true)][string]$Repository)
    $Key = (ConvertTo-PackTuneRepoKey $Repository).ToLower()
    $File = Get-PackTuneRepoPath "repo-tokens.json"
    if (-not (Test-Path -LiteralPath $File)) { return }
    $Data = @{}
    (Get-Content -LiteralPath $File -Raw | ConvertFrom-Json).PSObject.Properties | ForEach-Object { if ($_.Name -ne $Key) { $Data[$_.Name] = $_.Value } }
    ConvertTo-Json -InputObject $Data -Depth 4 | Set-Content -LiteralPath $File -Encoding UTF8
}

function Add-PackTuneRepository {
    <#
        Connects a repository: owner/name or URL. Public repositories need no token; a private one needs a fine-grained token
        with Contents (read) on that repository only. The repository is pinned by owner/name and its numeric id. A public
        repository is a third-party source (read only, never a Move target) unless -Own is given.
    #>
    param([Parameter(Mandatory = $true)][string]$Repository, [string]$Token, [string]$DisplayName, [switch]$Own, [switch]$RequireSignedCommits)
    $Key = ConvertTo-PackTuneRepoKey $Repository
    $Owner, $Name = $Key.Split("/")
    if (@(Get-PackTuneRepositories | Where-Object { "$($_.Owner)/$($_.Repo)".ToLower() -eq $Key.ToLower() }).Count) { throw "$Key is connected already." }
    $Info = (Invoke-PackTuneGitHubApi -Path "/repos/$Owner/$Name" -Token $Token).Body
    if (-not $Info -or -not $Info.id) { throw "GitHub gave no repository for $Key." }
    $Label = if ($DisplayName) { $DisplayName.Trim() } else { [string]$Info.name }
    if ($Label -notmatch '^[A-Za-z0-9][A-Za-z0-9 ._-]{0,59}$') { throw "The display name may contain letters, digits, spaces, . _ -" }
    $Entry = [pscustomobject]@{
        Owner = [string]$Info.owner.login; Repo = [string]$Info.name; RepoId = [int64]$Info.id; Name = $Label
        Private = [bool]$Info.private; Fork = [bool]$Info.fork; DefaultBranch = [string]$Info.default_branch
        ThirdParty = ((-not [bool]$Info.private) -and (-not $Own)); RequireSigned = [bool]$RequireSignedCommits
    }
    if ($Token) { Set-PackTuneRepoToken -Repository $Key -Token $Token }
    Save-PackTuneRepositories (@(Get-PackTuneRepositories) + $Entry)
    try { $null = Get-PackTuneRepoIndex -Repository $Key -Refresh } catch { Write-Warning "Connected, but the index could not be read yet: $($_.Exception.Message)" }
    return $Entry
}

function Remove-PackTuneRepository {
    # Removes the connection, the token and the cache; the approvals stay (they are a record of what was approved)
    param([Parameter(Mandatory = $true)][string]$Repository)
    $Found = Get-PackTuneRepository $Repository
    $Key = "$($Found.Owner)/$($Found.Repo)"
    Save-PackTuneRepositories @(Get-PackTuneRepositories | Where-Object { "$($_.Owner)/$($_.Repo)".ToLower() -ne $Key.ToLower() })
    Remove-PackTuneRepoToken $Key
    Remove-Item -LiteralPath (Get-PackTuneRepoPath ("repos\" + $Key.Replace("/", "__"))) -Recurse -Force -ErrorAction SilentlyContinue
}

function Grant-PackTuneRepoWrite {
    # The separate, explicit write grant (Contents: write on this one repository), needed only for Move. Refused for third-party sources.
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$Token)
    $Found = Get-PackTuneRepository $Repository
    if ($Found.ThirdParty) { throw "$($Found.Owner)/$($Found.Repo) is a third-party source: read only." }
    $Info = (Invoke-PackTuneGitHubApi -Path "/repos/$($Found.Owner)/$($Found.Repo)" -Token $Token).Body
    if ([int64]$Info.id -ne [int64]$Found.RepoId) { throw "This token reaches another repository (id differs): not stored." }
    if (-not $Info.permissions -or -not $Info.permissions.push) { throw "The token has no write access (Contents: write) to $($Found.Owner)/$($Found.Repo): not stored." }
    Set-PackTuneRepoToken -Repository "$($Found.Owner)/$($Found.Repo)" -Token $Token -Write
}

