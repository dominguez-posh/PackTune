function New-PackTuneRepositoryTemplate {
    <#
        "Create repository from template": copies the template repository layout (docs\repository-template) into a local folder and
        runs git init. It creates nothing on github.com: the printed next steps (gh repo create or the website) are for you to run.
    #>
    param([Parameter(Mandatory = $true)][string]$Destination, [string]$Name = "PackTune packages")
    $Template = Join-Path $PSScriptRoot "docs\repository-template"
    if (-not (Test-Path -LiteralPath $Template)) { throw "The template folder $Template is missing." }
    if ((Test-Path -LiteralPath $Destination) -and @(Get-ChildItem -LiteralPath $Destination -Force).Count) { throw "$Destination is not empty." }
    New-Item -ItemType Directory -Path $Destination -Force | Out-Null
    Copy-Item -Path (Join-Path $Template "*") -Destination $Destination -Recurse -Force
    $IndexFile = Join-Path $Destination $script:RepoIndexName
    $Index = Get-Content -LiteralPath $IndexFile -Raw | ConvertFrom-Json
    $Index.name = $Name
    ConvertTo-Json -InputObject $Index -Depth 6 | Set-Content -LiteralPath $IndexFile -Encoding UTF8
    $Git = Get-Command git -ErrorAction SilentlyContinue
    if ($Git) { Push-Location $Destination; try { & git init -q -b main 2>&1 | Out-Null } finally { Pop-Location } }
    Write-Host "Template written to $Destination. Create the private repository yourself, for example:`n  gh repo create <owner>/<name> --private --source `"$Destination`" --push`nThen protect the default branch (see docs\REPOSITORIES.md) and connect it in PackTune."
    return $Destination
}

function Test-PackTuneRepositoryClone {
    <# Check-PackTuneRepository: validates a local clone (index, manifests, every file hash, release-asset files excluded) without any network. #>
    param([Parameter(Mandatory = $true)][string]$Path)
    $Problems = New-Object System.Collections.ArrayList
    $IndexFile = Join-Path $Path $script:RepoIndexName
    if (-not (Test-Path -LiteralPath $IndexFile)) { return @("No $($script:RepoIndexName) in $Path.") }
    try { $Index = Get-Content -LiteralPath $IndexFile -Raw | ConvertFrom-Json } catch { return @("The index is not valid JSON.") }
    foreach ($P in @(Test-PackTuneRepoIndex $Index)) { [void]$Problems.Add($P) }
    if ($Problems.Count) { return @($Problems) }
    foreach ($App in @($Index.apps)) {
        foreach ($V in @($App.versions)) {
            $Dir = Join-Path $Path ([string]$V.path)
            $ManifestFile = Join-Path $Dir "manifest.json"
            if (-not (Test-Path -LiteralPath $ManifestFile)) { [void]$Problems.Add("$($App.id) $($V.version): manifest.json is missing."); continue }
            if ((Get-FileHash -LiteralPath $ManifestFile -Algorithm SHA256).Hash.ToLower() -ne ([string]$V.manifest).ToLower()) { [void]$Problems.Add("$($App.id) $($V.version): the manifest does not match the index."); continue }
            $Manifest = Get-Content -LiteralPath $ManifestFile -Raw | ConvertFrom-Json
            $Assets = @($V.assets | Where-Object { $_ })
            foreach ($F in @($Manifest.files)) {
                if ([string]$F.name -in $Assets) { continue }
                $File = Join-Path $Dir ([string]$F.name)
                if (-not (Test-Path -LiteralPath $File)) { [void]$Problems.Add("$($App.id) $($V.version): $($F.name) is missing."); continue }
                if ((Get-FileHash -LiteralPath $File -Algorithm SHA256).Hash.ToLower() -ne ([string]$F.sha256).ToLower()) { [void]$Problems.Add("$($App.id) $($V.version): $($F.name) does not match the manifest.") }
            }
        }
    }
    return @($Problems)
}
Set-Alias -Name Check-PackTuneRepository -Value Test-PackTuneRepositoryClone

