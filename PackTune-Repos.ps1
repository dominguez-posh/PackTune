function Test-PackTuneRepoApproved {
    # A version is approved only for exactly the manifest hash that was shown: a changed manifest needs a new approval
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$AppId, [Parameter(Mandatory = $true)][string]$Version, [Parameter(Mandatory = $true)][string]$Manifest)
    $Key = (ConvertTo-PackTuneRepoKey $Repository).ToLower()
    return [bool](@(Get-PackTuneRepoApprovals | Where-Object { $_.Repository.ToLower() -eq $Key -and $_.AppId -eq $AppId -and $_.Version -eq $Version -and $_.Manifest -eq $Manifest.ToLower() }).Count)
}

function Get-PackTuneRepoCommitInfo {
    # Latest commit that touched the path: sha, author, date, message, signature state (GitHub's verification)
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$Path)
    $Found = Get-PackTuneRepository $Repository
    $Response = Invoke-PackTuneGitHubApi -Path "/repos/$($Found.Owner)/$($Found.Repo)/commits?path=$([uri]::EscapeDataString($Path))&per_page=1" -Token (Get-PackTuneRepoToken "$($Found.Owner)/$($Found.Repo)")
    $Commit = @($Response.Body) | Select-Object -First 1
    if (-not $Commit) { throw "GitHub shows no commit for $Path." }
    [pscustomobject]@{
        Sha = [string]$Commit.sha; Author = [string]$Commit.commit.author.name; Login = [string]$Commit.author.login; Date = [string]$Commit.commit.author.date
        Message = ([string]$Commit.commit.message -split "`n")[0]; Verified = [bool]$Commit.commit.verification.verified; VerificationReason = [string]$Commit.commit.verification.reason
    }
}

function Get-PackTuneRepoVersionEntry {
    param($Index, [string]$AppId, [string]$Version)
    $App = @($Index.Apps | Where-Object { $_.id -eq $AppId }) | Select-Object -First 1
    if (-not $App) { throw "$AppId is not in the index of the repository." }
    $Entry = @($App.versions | Where-Object { [string]$_.version -eq $Version }) | Select-Object -First 1
    if (-not $Entry) { throw "$AppId $Version is not in the index of the repository." }
    [pscustomobject]@{ App = $App; Version = $Entry }
}

function Read-PackTuneRepoManifest {
    # Downloads manifest.json of one version, checks size, hash against the index entry and format; returns Hash, Manifest, File
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$AppId, [Parameter(Mandatory = $true)][string]$Version, [Parameter(Mandatory = $true)][string]$Destination, [string]$IndexManifest)
    foreach ($S in $AppId, $Version) { if ($S -notmatch $script:StoreSegment) { throw "'$S' is not a valid app id or version." } }
    $null = Get-PackTuneRepoContent -Repository $Repository -Segments @("apps", $AppId, $Version, "manifest.json") -Destination $Destination
    if ((Get-Item -LiteralPath $Destination).Length -gt $script:RepoManifestMaxBytes) { Remove-Item -LiteralPath $Destination -Force; throw "The manifest is larger than allowed: refused." }
    $Hash = (Get-FileHash -LiteralPath $Destination -Algorithm SHA256).Hash.ToLower()
    if ($IndexManifest -and $Hash -ne $IndexManifest.ToLower()) { Remove-Item -LiteralPath $Destination -Force; throw "The manifest of $AppId $Version does not match the hash in the index: the repository is damaged or was changed. Nothing was used." }
    $Manifest = Get-Content -LiteralPath $Destination -Raw | ConvertFrom-Json
    if ($Manifest.format -ne "PackTune.Store" -or $Manifest.app -ne $AppId -or $Manifest.appVersion -ne $Version) { throw "The manifest does not belong to $AppId $Version." }
    foreach ($Entry in @($Manifest.files)) {
        if ([string]$Entry.name -notin $script:StoreFileNames) { throw "The manifest names an unexpected file '$($Entry.name)'." }
        if ([string]$Entry.sha256 -notmatch '^[0-9A-Fa-f]{64}$') { throw "The manifest has no valid hash for $($Entry.name)." }
        if ([int64]$Entry.size -lt 0 -or [int64]$Entry.size -gt $script:RepoFileMaxBytes) { throw "$($Entry.name) is larger than the 2 GB a release asset can hold." }
    }
    [pscustomobject]@{ Hash = $Hash; Manifest = $Manifest; File = $Destination }
}

function Get-PackTuneRepoApprovalRequest {
    <#
        What the person sees before approving a version: repository (third-party label), app, version, commit (sha, author, date,
        message, signature state), the files with sizes and hashes, and what changed against the last approved version.
        Blocked says why a version cannot be approved at all (required signature missing, index and manifest disagree).
    #>
    param([Parameter(Mandatory = $true)][string]$Repository, [Parameter(Mandatory = $true)][string]$AppId, [Parameter(Mandatory = $true)][string]$Version)
    $State = Assert-PackTuneRepoReady $Repository
    $Repo = $State.Repository
    $Key = "$($Repo.Owner)/$($Repo.Repo)"
    $Index = Get-PackTuneRepoIndex -Repository $Key
    if ($Index.Damaged) { throw "The repository index is damaged: $($Index.Problems -join ' ')" }
    $Entry = Get-PackTuneRepoVersionEntry -Index $Index -AppId $AppId -Version $Version
    $Temp = Join-Path ([IO.Path]::GetTempPath()) ("packtune-approve-" + [guid]::NewGuid().ToString("N").Substring(0, 8))
    New-Item -ItemType Directory -Path $Temp -Force | Out-Null
    try {
        $Blocked = $null
        $Read = $null
        try { $Read = Read-PackTuneRepoManifest -Repository $Key -AppId $AppId -Version $Version -Destination (Join-Path $Temp "manifest.json") -IndexManifest ([string]$Entry.Version.manifest) }
        catch { $Blocked = $_.Exception.Message }
        $Commit = Get-PackTuneRepoCommitInfo -Repository $Key -Path "apps/$AppId/$Version"
        if (-not $Blocked -and $Repo.RequireSigned -and -not $Commit.Verified) { $Blocked = "This repository requires verified commits and the commit $($Commit.Sha.Substring(0, 7)) is not verified by GitHub ($($Commit.VerificationReason))." }
        $Previous = @(Get-PackTuneRepoApprovals | Where-Object { $_.Repository.ToLower() -eq $Key.ToLower() -and $_.AppId -eq $AppId -and $_.Version -ne $Version } | Sort-Object { try { [version]$_.Version } catch { [version]"0.0" } } -Descending) | Select-Object -First 1
        $Old = @{}; if ($Previous) { foreach ($F in @($Previous.Files)) { $Old[[string]$F.name] = [string]$F.sha256 } }
        $Files = if ($Read) { @($Read.Manifest.files | ForEach-Object {
                    $Status = if (-not $Previous) { "new" } elseif (-not $Old.ContainsKey([string]$_.name)) { "new" } elseif ($Old[[string]$_.name] -ne ([string]$_.sha256).ToLower() -and $Old[[string]$_.name] -ne [string]$_.sha256) { "changed" } else { "unchanged" }
                    [pscustomobject]@{ Name = [string]$_.name; Size = [int64]$_.size; Sha256 = ([string]$_.sha256).ToLower(); Status = $Status }
                }) } else { @() }
        [pscustomobject]@{
            Repository = $Key; Label = (Get-PackTuneRepoLabel $Repo); ThirdParty = [bool]$Repo.ThirdParty; Private = [bool]$Repo.Private; RequireSigned = [bool]$Repo.RequireSigned
            AppId = $AppId; Name = [string]$Entry.App.name; Version = $Version; Kind = [string]$Entry.App.kind
            Manifest = $(if ($Read) { $Read.Hash } else { ([string]$Entry.Version.manifest).ToLower() }); Commit = $Commit; Files = $Files
            PreviousVersion = $(if ($Previous) { [string]$Previous.Version } else { $null }); Blocked = $Blocked
        }
    }
    finally { Remove-Item -LiteralPath $Temp -Recurse -Force -ErrorAction SilentlyContinue }
}

function Approve-PackTuneRepoVersion {
    <# Records the approval of exactly what the request showed. A blocked request or one that no longer matches the repository is refused. #>
    param([Parameter(Mandatory = $true)]$Request)
    if ($Request.Blocked) { throw "Cannot be approved: $($Request.Blocked)" }
    $Now = Get-PackTuneRepoApprovalRequest -Repository $Request.Repository -AppId $Request.AppId -Version $Request.Version
    if ($Now.Blocked -or $Now.Manifest -ne $Request.Manifest -or $Now.Commit.Sha -ne $Request.Commit.Sha) { throw "The repository changed since the approval dialog was shown: look at it again." }
    $Record = [pscustomobject]@{
        Repository = $Request.Repository; AppId = $Request.AppId; Version = $Request.Version; Manifest = $Request.Manifest
        Commit = $Request.Commit.Sha; Author = $Request.Commit.Author; Verified = $Request.Commit.Verified
        ApprovedBy = $env:USERNAME; Approved = (Get-Date).ToUniversalTime().ToString("o")
        Files = @($Request.Files | ForEach-Object { [pscustomobject]@{ name = $_.Name; sha256 = $_.Sha256; size = $_.Size } })
    }
    $Rest = @(Get-PackTuneRepoApprovals | Where-Object { -not ($_.Repository.ToLower() -eq $Request.Repository.ToLower() -and $_.AppId -eq $Request.AppId -and $_.Version -eq $Request.Version) })
    New-Item -ItemType Directory -Path $script:WorkRoot -Force | Out-Null
    ConvertTo-Json -InputObject @($Rest + $Record) -Depth 6 | Set-Content -LiteralPath (Get-PackTuneRepoPath "repo-approvals.json") -Encoding UTF8
    return $Record
}

