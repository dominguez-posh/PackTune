<#
.SYNOPSIS
    Live check of the device notifications in Windows Sandbox: notify.ps1 as generated by PackTune runs as the sandbox user, shows
    its toasts (update prompt, deadline reminder, closing notice), the buttons are pressed through the real packtune-update: protocol
    (registered in HKCU by the script), a fake SYSTEM task "Update Contoso.Tool now" proves "Install now", a wrong token proves that
    nothing else happens. Screenshots and results.json land in the output folder. Nothing runs on this computer.
.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\Tests\Spike-Toast.ps1
#>
[CmdletBinding()]
param([int]$TimeoutMinutes = 6, [string]$OutDir)
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
if (-not (Test-Path "$env:SystemRoot\System32\WindowsSandbox.exe")) { throw 'Windows Sandbox is not available on this machine.' }
if (Get-Process -Name WindowsSandbox, WindowsSandboxClient, WindowsSandboxRemoteSession -ErrorAction SilentlyContinue) { throw 'A Windows Sandbox is already running; Windows allows only one.' }
$work = Join-Path ([IO.Path]::GetTempPath()) ('PackTuneToastSpike-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -ItemType Directory -Path $work -Force | Out-Null
$env:LOCALAPPDATA = $work
. (Join-Path $repo 'PackTune-Main.ps1')
$job = Join-Path $work 'job'
New-Item -ItemType Directory -Path (Join-Path $job 'out') -Force | Out-Null
Set-Content -Path (Join-Path $job 'notify.ps1') -Value (Get-UpdateNotifyScript -TaskPath '\PackTune\Winget\') -Encoding ASCII

$run = @'
$ErrorActionPreference = 'Continue'
$Job = 'C:\Job'; $Out = "$Job\out"
$R = [ordered]@{}
function Shot($Name) {
    Add-Type -AssemblyName System.Windows.Forms, System.Drawing
    $b = [System.Windows.Forms.Screen]::PrimaryScreen.Bounds
    $bmp = New-Object System.Drawing.Bitmap $b.Width, $b.Height
    $g = [System.Drawing.Graphics]::FromImage($bmp); $g.CopyFromScreen($b.Location, [System.Drawing.Point]::Empty, $b.Size)
    $bmp.Save("$Out\$Name.png", [System.Drawing.Imaging.ImageFormat]::Png); $g.Dispose(); $bmp.Dispose()
}
function Save-Result { $R | ConvertTo-Json | Set-Content "$Job\result.json" -Encoding UTF8 }
function Show-Notify { Start-Process -FilePath powershell.exe -ArgumentList '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', "`"$Root\notify.ps1`"" -RedirectStandardError "$Out\notify-stderr.txt" -PassThru | Out-Null }
function Get-Token { (Get-ChildItem "$env:LOCALAPPDATA\PackTune\Updates\toasts" -Filter *.json -ErrorAction SilentlyContinue | Sort-Object LastWriteTime | Select-Object -Last 1).BaseName }
try {
    # the console of this script out of the way (the toasts come up at the bottom right)
    Add-Type -Name Win -Namespace PackTuneSpike -MemberDefinition '[System.Runtime.InteropServices.DllImport("kernel32.dll")] public static extern System.IntPtr GetConsoleWindow(); [System.Runtime.InteropServices.DllImport("user32.dll")] public static extern bool ShowWindow(System.IntPtr h, int n); [System.Runtime.InteropServices.DllImport("user32.dll")] public static extern bool SetProcessDPIAware();'
    [void][PackTuneSpike.Win]::ShowWindow([PackTuneSpike.Win]::GetConsoleWindow(), 6); [void][PackTuneSpike.Win]::SetProcessDPIAware()
    $R.Started = $true; Save-Result
    Add-Type -AssemblyName System.Drawing
    $Root = "$env:ProgramFiles\PackTune\Winget\Contoso.Tool"
    New-Item -ItemType Directory -Path $Root -Force | Out-Null
    Copy-Item "$Job\notify.ps1" $Root
    # an icon for the package: a blue tile with a letter
    $bmp = New-Object System.Drawing.Bitmap 96, 96
    $g = [System.Drawing.Graphics]::FromImage($bmp); $g.Clear([System.Drawing.ColorTranslator]::FromHtml('#005FB8'))
    $g.DrawString('C', (New-Object System.Drawing.Font('Segoe UI', 44, [System.Drawing.FontStyle]::Bold)), [System.Drawing.Brushes]::White, 12, 6)
    $bmp.Save("$Root\icon.png", [System.Drawing.Imaging.ImageFormat]::Png); $g.Dispose(); $bmp.Dispose()
    @{ Id = 'Contoso.Tool'; SafeId = 'Contoso.Tool'; TaskId = 'Contoso.Tool'; TaskPath = '\PackTune\Winget\'; DisplayName = 'Contoso' } | ConvertTo-Json | Set-Content "$Root\config.json"
    function Set-State($Deadline, $CloseAt) {
        $s = @{ Package = 'Contoso.Tool'; DisplayName = 'Contoso & Co <Pro>'; Deadline = $Deadline.ToString('o'); Installed = '1.0'; Target = '2.0' }
        if ($CloseAt) { $s.CloseAt = $CloseAt.ToString('o') }
        $s | ConvertTo-Json | Set-Content "$Root\state.json"
    }
    # the "Update Contoso.Tool now" SYSTEM task, replaced by one that leaves a marker
    $action = New-ScheduledTaskAction -Execute cmd.exe -Argument '/c echo ran > C:\Job\task-ran.txt'
    Register-ScheduledTask -TaskName 'Update Contoso.Tool now' -TaskPath '\PackTune\Winget\' -Action $action -User 'SYSTEM' -RunLevel Highest -Force | Out-Null
    Start-Sleep -Seconds 20   # the desktop settles

    # what Windows says about toasts for the app before anything is shown
    try {
        $src = Get-Content "$Root\notify.ps1" -Raw
        $lib = $src.Substring($src.IndexOf('# ---------------------------------------------------------------- notifications'), $src.IndexOf('$TaskPath = "\PackTune') - $src.IndexOf('# ---------------------------------------------------------------- notifications'))
        $SnoozeFolder = "$env:LOCALAPPDATA\PackTune\Updates"
        Invoke-Expression $lib
        $st = Get-ToastState
        $R.ToastSetting = $st.Setting; $R.ShellState = $st.UserState
        $R.RouteForPrompt = Get-ToastRoute -Setting $st.Setting -UserState $st.UserState -Deadline $false
        $xml = New-ToastXml -Title 'Diagnostics' -Lines @('direct toast') -IconFile "$Root\icon.png" -Buttons @(@{ Text = 'OK'; System = 'dismiss' }) -Reminder $false
        $R.DirectToast = Show-ToastXml 'diag' $xml
        $R.DirectToastLog = (Get-Content "$SnoozeFolder\notify.log" -ErrorAction SilentlyContinue) -join ' | '
        Start-Sleep -Seconds 3; Shot '0-direct-toast'
    }
    catch { $R.DiagError = $_.Exception.Message }
    Save-Result
    Start-Sleep -Seconds 6

    # 1. update prompt, deadline in 5 hours
    Set-State (Get-Date).AddHours(5) $null
    Show-Notify; Start-Sleep -Seconds 9; Shot '1-update-toast'
    $R.AppRegistered = (Get-ItemProperty 'HKCU:\Software\Classes\AppUserModelId\PackTune.Updates' -ErrorAction SilentlyContinue).DisplayName
    $R.ProtocolCommand = (Get-ItemProperty 'HKCU:\Software\Classes\packtune-update\shell\open\command' -ErrorAction SilentlyContinue).'(default)'
    $Token = Get-Token; $R.Token = [bool]$Token
    $R.NotifyLog = (Get-Content "$env:LOCALAPPDATA\PackTune\Updates\notify.log" -ErrorAction SilentlyContinue) -join " | "
    Save-Result
    Start-Sleep -Seconds 8

    # 2. a wrong token through the protocol: nothing happens
    Remove-Item "$Job\task-ran.txt" -Force -ErrorAction SilentlyContinue
    Start-Process "packtune-update:install?t=00000000000000000000000000000000"; Start-Sleep -Seconds 12
    $R.WrongTokenStartedTask = Test-Path "$Job\task-ran.txt"
    Start-Process "packtune-update:install?t=$Token&x=1"; Start-Sleep -Seconds 12
    $R.ExtraParameterStartedTask = Test-Path "$Job\task-ran.txt"

    # 3. "Install now": the real protocol, as Windows starts it for a button
    Start-Process "packtune-update:install?t=$Token"
    for ($i = 0; $i -lt 40 -and -not (Test-Path "$Job\task-ran.txt"); $i++) { Start-Sleep -Seconds 1 }
    $R.InstallNowStartedTask = Test-Path "$Job\task-ran.txt"
    Start-Sleep -Seconds 4; Shot '2-install-now-result'
    Save-Result
    Start-Sleep -Seconds 6
    Remove-Item "$Job\task-ran.txt" -Force -ErrorAction SilentlyContinue
    Start-Process "packtune-update:install?t=$Token"; Start-Sleep -Seconds 8
    $R.ReplayStartedTask = Test-Path "$Job\task-ran.txt"
    Save-Result

    # 4. deadline within the hour: a reminder that stays
    Set-State (Get-Date).AddMinutes(30) $null
    Show-Notify; Start-Sleep -Seconds 12; Shot '3-reminder-toast-after-12s'

    # 5. closing notice after the deadline
    Set-State (Get-Date).AddMinutes(-5) (Get-Date).AddMinutes(25)
    Show-Notify; Start-Sleep -Seconds 8; Shot '4-closing-toast'

    # 6. the fallback window itself (what notify.ps1 shows when toasts are off or Focus assist hides the deadline notice)
    $win = "`$SnoozeFolder = `"$env:LOCALAPPDATA\PackTune\Updates`"`r`n" + $lib + "`r`n" + 'Show-UpdateWindow -Title "Software update: Contoso & Co <Pro>" -Message "Contoso & Co <Pro> is updated now and will be closed at 15:17.`r`n`r`nPlease save your work and close Contoso & Co <Pro>." -Buttons @(@{ Text = "Install now"; Result = "install"; Primary = $true }, @{ Text = "Later"; Result = "later" }) -IconFile "' + "$Root\icon.png" + '"'
    Set-Content -Path "$Job\window.ps1" -Value $win -Encoding ASCII
    $p = Start-Process -FilePath powershell.exe -ArgumentList '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', 'C:\Job\window.ps1' -PassThru
    Start-Sleep -Seconds 14; Shot '5-fallback-window'
    $R.FallbackWindowOpen = -not $p.HasExited
    if (-not $p.HasExited) { Stop-Process -Id $p.Id -Force }
    $R.NotifyLog = (Get-Content "$env:LOCALAPPDATA\PackTune\Updates\notify.log" -ErrorAction SilentlyContinue) -join " | "
    $R.Status = 'done'
}
catch { $R.Error = $_.Exception.Message }
$R | ConvertTo-Json | Set-Content "$Job\result.json" -Encoding UTF8
Start-Sleep -Seconds 2
shutdown.exe /s /t 0
'@
Set-Content -Path (Join-Path $job 'run.ps1') -Value $run -Encoding ASCII
$esc = { param($s) [Security.SecurityElement]::Escape($s) }
$wsb = @"
<Configuration>
  <vGPU>Enable</vGPU>
  <Networking>Disable</Networking>
  <MemoryInMB>4096</MemoryInMB>
  <MappedFolders>
    <MappedFolder><HostFolder>$(& $esc $job)</HostFolder><SandboxFolder>C:\Job</SandboxFolder><ReadOnly>false</ReadOnly></MappedFolder>
  </MappedFolders>
  <LogonCommand><Command>powershell.exe -NoProfile -ExecutionPolicy Bypass -File C:\Job\run.ps1</Command></LogonCommand>
</Configuration>
"@
Set-Content -Path (Join-Path $work 'toast.wsb') -Value $wsb -Encoding UTF8
Start-Process -FilePath "$env:SystemRoot\System32\WindowsSandbox.exe" -ArgumentList "`"$(Join-Path $work 'toast.wsb')`""
$resultFile = Join-Path $job 'result.json'
$deadline = (Get-Date).AddMinutes($TimeoutMinutes)
while ((-not (Test-Path $resultFile) -or (Get-Content $resultFile -Raw -ErrorAction SilentlyContinue) -notmatch 'Status') -and (Get-Date) -lt $deadline) { Start-Sleep -Seconds 5 }
if ((Get-Content $resultFile -Raw -ErrorAction SilentlyContinue) -notmatch 'Status') { if ($OutDir) { New-Item -ItemType Directory -Path $OutDir -Force | Out-Null; Copy-Item (Join-Path $job 'out\*') $OutDir -Force -ErrorAction SilentlyContinue }; Get-Content $resultFile -Raw -ErrorAction SilentlyContinue; throw "No result after $TimeoutMinutes minutes (job folder: $job)" }
$result = Get-Content $resultFile -Raw | ConvertFrom-Json
if ($OutDir) { New-Item -ItemType Directory -Path $OutDir -Force | Out-Null; Copy-Item (Join-Path $job 'out\*') $OutDir -Force; Copy-Item $resultFile $OutDir -Force }
$result | Format-List | Out-String
$checks = @(
    @('the app is registered as PackTune Updates', ($result.AppRegistered -eq 'PackTune Updates')),
    @('the protocol is registered and points at notify.ps1 -Activate', [bool]($result.ProtocolCommand -like '*notify.ps1*-Activate*')),
    @('a token was written for the toast', [bool]$result.Token),
    @('a wrong token starts nothing', ($result.WrongTokenStartedTask -eq $false)),
    @('an address with extra parameters starts nothing', ($result.ExtraParameterStartedTask -eq $false)),
    @('Install now (the protocol with the real token) starts the update task', ($result.InstallNowStartedTask -eq $true)),
    @('the same address a second time starts nothing (token used up)', ($result.ReplayStartedTask -eq $false)),
    @('toasts off: the PackTune window opens instead', ($result.FallbackWindowOpen -eq $true))
)
$failed = 0
foreach ($c in $checks) { if ($c[1]) { "PASS  $($c[0])" } else { $failed++; "FAIL  $($c[0])" } }
if ($result.Error) { "ERROR in the sandbox: $($result.Error)"; $failed++ }
Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue
if ($failed) { throw "$failed check(s) failed" }
'SPIKE PASSED'
